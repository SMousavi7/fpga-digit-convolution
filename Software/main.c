static inline void conv_write(uint32_t offset, uint32_t value)
{
    Xil_Out32((UINTPTR)(CONV_BASEADDR + offset), value);
}

static inline uint32_t conv_read(uint32_t offset)
{
    return Xil_In32((UINTPTR)(CONV_BASEADDR + offset));
}

static int wait_status_set(uint32_t mask)
{
    uint32_t timeout = POLL_TIMEOUT;

    while (timeout-- != 0U) {
        const uint32_t status = conv_read(REG_STATUS);

        if ((status & STATUS_ERROR) != 0U) {
            xil_printf("ERROR: FPGA status = 0x%08lx\r\n",
                       (unsigned long)status);
            return -1;
        }

        if ((status & mask) == mask) {
            return 0;
        }
    }

    xil_printf("ERROR: timeout waiting for status mask 0x%08lx\r\n",
               (unsigned long)mask);
    return -1;
}

static int wait_chunk_finished(uint8_t last_chunk)
{
    uint32_t timeout = POLL_TIMEOUT;
    uint8_t busy_seen = 0U;

    while (timeout-- != 0U) {
        const uint32_t status = conv_read(REG_STATUS);

        if ((status & STATUS_ERROR) != 0U) {
            xil_printf("ERROR: FPGA status = 0x%08lx\r\n",
                       (unsigned long)status);
            return -1;
        }

        if ((status & STATUS_BUSY) != 0U) {
            busy_seen = 1U;
        }

        if (busy_seen != 0U &&
            (status & STATUS_BUSY) == 0U &&
            (status & STATUS_CHUNK_DONE) != 0U) {
            if (last_chunk == 0U || (status & STATUS_DONE) != 0U) {
                return 0;
            }
        }
    }

    xil_printf("ERROR: convolution timeout\r\n");
    return -1;
}

static uint32_t make_config(const ChunkConfig *chunk)
{
    return ((uint32_t)chunk->base_row) |
           ((uint32_t)chunk->rows << 8) |
           ((uint32_t)chunk->scan_rows << 16) |
           ((uint32_t)chunk->last_chunk << 24);
}

static uint32_t pack_four_pixels(uint32_t image_index)
{
    return ((uint32_t)image[image_index]     << 24) |
           ((uint32_t)image[image_index + 1U] << 16) |
           ((uint32_t)image[image_index + 2U] << 8) |
           ((uint32_t)image[image_index + 3U]);
}

static int send_chunk(const ChunkConfig *chunk, uint32_t chunk_number)
{
    uint32_t local_row;
    uint32_t word_in_row;

    xil_printf("Sending chunk %lu: rows %u..%u\r\n",
               (unsigned long)chunk_number,
               (unsigned int)chunk->base_row,
               (unsigned int)(chunk->base_row + chunk->rows - 1U));

    conv_write(REG_CONFIG, make_config(chunk));

    for (local_row = 0U; local_row < chunk->rows; ++local_row) {
        const uint32_t global_row =
            (uint32_t)chunk->base_row + local_row;

        for (word_in_row = 0U;
             word_in_row < WORDS_PER_ROW;
             ++word_in_row) {
            const uint32_t pixel_index =
                global_row * IMAGE_WIDTH + word_in_row * 4U;

            if (wait_status_set(STATUS_WORD_READY) != 0) {
                return -1;
            }

            conv_write(REG_PIXEL_DATA,
                       pack_four_pixels(pixel_index));
        }
    }

    xil_printf("Chunk %lu loaded (%lu words), processing...\r\n",
               (unsigned long)chunk_number,
               (unsigned long)(chunk->rows * WORDS_PER_ROW));

    conv_write(REG_CONTROL, CONTROL_CHUNK_START);

    if (wait_chunk_finished(chunk->last_chunk) != 0) {
        return -1;
    }

    xil_printf("Chunk %lu finished\r\n",
               (unsigned long)chunk_number);

    return 0;
}

